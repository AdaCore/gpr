#!/usr/bin/env python3
"""Generate GPR2.Unicode from the Unicode CaseFolding.txt C/S mappings.

Usage: generate_unicode_case_folding.py CaseFolding.txt [output.adb]
The checked-in table uses Unicode 13 (ISO/IEC 10646:2020, Ada 2022).
"""

import argparse
from bisect import bisect_right
from pathlib import Path


def generate(source):
    mappings = {}
    for line in source.splitlines():
        fields = line.split("#", 1)[0].split(";")
        if len(fields) > 2 and fields[1].strip() in ("C", "S"):
            values = fields[2].split()
            assert len(values) == 1
            mappings[int(fields[0], 16)] = int(values[0], 16)

    ranges = []
    items = sorted(mappings.items())
    index = 0
    while index < len(items):
        first, target = items[index]
        last = first
        delta = target - first
        step = 1
        if index + 1 < len(items):
            next_code, next_target = items[index + 1]
            if next_code - first in (1, 2) and next_target - next_code == delta:
                step = next_code - first
        index += 1
        while index < len(items):
            code, target = items[index]
            if code != last + step or target - code != delta:
                break
            last = code
            index += 1
        ranges.append((first, last, step, delta))

    # Check gaps and range boundaries as well as the mapped characters.
    starts = [r[0] for r in ranges]
    for code in range(0x110000):
        pos = bisect_right(starts, code) - 1
        folded = code
        if pos >= 0:
            first, last, step, delta = ranges[pos]
            if code <= last and (code - first) % step == 0:
                folded += delta
        assert folded == mappings.get(code, code), hex(code)

    rows = []
    for first, last, step, delta in ranges:
        rows.append(f"      (16#{first:06X}#, 16#{last:06X}#, {step}, {delta})")
    version = source.splitlines()[0].removeprefix("# ")
    table = ",\n".join(rows)
    return f'''--
--  Copyright (C) 2026, AdaCore
--
--  SPDX-License-Identifier: Apache-2.0 WITH LLVM-Exception
--
--  Generated by utilities/generate_unicode_case_folding.py from
--  {version}, C and S entries only. Do not edit the table.
--  Unicode data copyright 2019 Unicode, Inc. See LICENSE-unicode.

with Ada.Strings.UTF_Encoding.Wide_Wide_Strings;
with Ada.Wide_Wide_Characters.Handling;

with GNAT.Decode_UTF8_String;

package body GPR2.Unicode is

   type Fold_Range is record
      First, Last : Natural;
      Step        : Positive;
      Offset      : Integer;
   end record;

   Ranges : constant array (Positive range <>) of Fold_Range :=
     (
{table});

   function Fold (Value : Wide_Wide_Character) return Wide_Wide_Character;

   ----------
   -- Fold --
   ----------

   function Fold (Value : Wide_Wide_Character) return Wide_Wide_Character is
      Code : constant Natural := Wide_Wide_Character'Pos (Value);
      Low  : Natural := Ranges'First;
      High : Natural := Ranges'Last;
   begin
      while Low <= High loop
         declare
            Middle : constant Positive := (Low + High) / 2;
            Item   : Fold_Range renames Ranges (Middle);
         begin
            if Code < Item.First then
               High := Middle - 1;
            elsif Code > Item.Last then
               Low := Middle + 1;
            else
               return
                 (if (Code - Item.First) mod Item.Step = 0
                  then Wide_Wide_Character'Val (Code + Item.Offset)
                  else Value);
            end if;
         end;
      end loop;
      return Value;
   end Fold;

   ----------
   -- Fold --
   ----------

   function Fold (Text : String; Uppercase : Boolean := False) return String is
      Source  : constant String (1 .. Text'Length) := Text;
      Decoded : Wide_Wide_String (1 .. Text'Length);
      Length  : Natural := 0;
      Cursor  : Natural := Source'First;
      Value   : Wide_Wide_Character;
   begin
      --  Rebase the input for the decoder's one-past-end cursor

      while Cursor <= Source'Last loop
         if Source (Cursor) < Character'Val (16#80#) then
            Value := Wide_Wide_Character'Val (Character'Pos (Source (Cursor)));
            Cursor := Cursor + 1;
         else
            GNAT.Decode_UTF8_String.Decode_Wide_Wide_Character
              (Source, Cursor, Value);
         end if;

         Value := Fold (Value);
         if Uppercase then
            declare
               Upper : constant Wide_Wide_Character :=
                 Ada.Wide_Wide_Characters.Handling.To_Upper (Value);
            begin
               --  Uppercasing must not merge distinct simple-fold classes,
               --  such as Latin I and dotless i.

               if Fold (Upper) = Value then
                  Value := Upper;
               end if;
            end;
         end if;
         Length := Length + 1;
         Decoded (Length) := Value;
      end loop;

      return Ada.Strings.UTF_Encoding.Wide_Wide_Strings.Encode
        (Decoded (1 .. Length));
   end Fold;

end GPR2.Unicode;
'''


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("data", type=Path)
    parser.add_argument("output", nargs="?", type=Path,
                        default=Path("src/lib/gpr2-unicode.adb"))
    args = parser.parse_args()
    args.output.write_text(generate(args.data.read_text(encoding="utf-8")),
                           encoding="utf-8")
